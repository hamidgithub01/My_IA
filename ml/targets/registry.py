# TARGET TASK

# ==========================================================

def get_target_task(
target_name,
):
    """
    Return the machine-learning task type for a target.

    Returns:

        regression
        classification
        categorical
    """

    validate_target_registry()

    if target_name in REGRESSION_TARGETS:

        return 'regression'

    if target_name in BINARY_CLASSIFICATION_TARGETS:

        return 'classification'

    if target_name in CATEGORICAL_TARGETS:

        return 'categorical'

    raise ValueError(
        f'Unknown target: {target_name}'
    )


# ==========================================================

# PUBLIC HELPERS

# ==========================================================

def is_regression_target(
target_name,
):
    """
    Return True when target is a regression target.
    """

    
    return (
        get_target_task(
            target_name
        )
        == 'regression'
    )
    

def is_classification_target(
    target_name,
    ):
    """
    Return True when target is a binary classification
    target.
    """

    return (
        get_target_task(
            target_name
        )
        == 'classification'
    )


def is_categorical_target(target_name,):
    """
    Return True when target is a categorical target.
    """

    return (
        get_target_task(
            target_name
        )
        == 'categorical'
    )


# HORIZON HELPERS

# ==========================================================

def _get_all_horizons():
    """
    Return every horizon currently generated by the
    Target Builder.

    ```
    The order is deterministic and follows the project
    horizon definitions.
    """

    return (
        list(DAILY_HORIZONS)
        + list(PERIOD_HORIZONS)
    )


def _target_family(target_name):
    """
    Extract the target family from a generated target name.

    Example:

        Target_Expense_Total_1D
        ->
        Target_Expense_Total
    """

    for horizon in _get_all_horizons():

        suffix = f'_{horizon}'

        if target_name.endswith(suffix):

            return target_name[
                :-len(suffix)
            ]

    return None


def _build_family_targets(families):
    """
    Generate all concrete target names for the supplied
    target families using the current horizon definitions.
    """

    targets = set()

    for family in families:

        for horizon in _get_all_horizons():

            targets.add(
                f'{family}_{horizon}'
            )

    return targets



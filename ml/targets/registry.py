# VALIDATION

# ==========================================================

def validate_target_registry():
    """
    Validate that the target registry exactly matches the
    targets generated by the Target Builder.

    ```
    Checks:

        1. No generated target is missing.
        2. No registry target is unknown.
        3. No target belongs to multiple task groups.
        4. Every generated target has a known task type.
    """

    generated_targets = set(
        get_target_names()
    )

    registry_targets = (
        REGRESSION_TARGETS
        | BINARY_CLASSIFICATION_TARGETS
        | CATEGORICAL_TARGETS
    )

# ------------------------------------------------------
# Generated targets missing from registry
# ------------------------------------------------------

    missing = (
        generated_targets
        - registry_targets
    )

    if missing:

        raise ValueError(
            'Targets missing from registry: '
            f'{sorted(missing)}'
        )

    # ------------------------------------------------------
    # Registry targets that are not generated
    # ------------------------------------------------------

    unknown = (
        registry_targets
        - generated_targets
    )

    if unknown:

        raise ValueError(
            'Registry contains unknown targets: '
            f'{sorted(unknown)}'
        )

# ------------------------------------------------------
# Check overlaps
# ------------------------------------------------------

    groups = [
        REGRESSION_TARGETS,
        BINARY_CLASSIFICATION_TARGETS,
        CATEGORICAL_TARGETS,
    ]

    overlaps = []

    for index, first in enumerate(groups):

        for second in groups[index + 1:]:

            overlaps.extend(
                first & second
            )

    if overlaps:

        raise ValueError(
            'Targets appear in multiple registry groups: '
            f'{sorted(set(overlaps))}'
        )

    # ------------------------------------------------------
    # Check that every generated target has a family
    # ------------------------------------------------------

    unresolved = []

    for target_name in generated_targets:

        family = _target_family(
            target_name
        )

        if family is None:

            unresolved.append(
                target_name
            )

    if unresolved:

        raise ValueError(
            'Unable to determine target family for: '
            f'{sorted(unresolved)}'
        )

# ------------------------------------------------------
# Check that every target belongs to exactly one family
# ------------------------------------------------------

    family_sets = [
        REGRESSION_TARGET_FAMILIES,
        BINARY_CLASSIFICATION_TARGET_FAMILIES,
        CATEGORICAL_TARGET_FAMILIES,
    ]

    for target_name in generated_targets:

        family = _target_family(
            target_name
        )

        matches = sum(
            family in family_set
            for family_set in family_sets
        )

        if matches != 1:

            raise ValueError(
                'Target family has invalid task assignment: '
                f'{target_name}'
            )

    return True



# =========================================================
# DEFAULT TARGET
# =========================================================

DEFAULT_TARGET_NAME = (
    'Target_Expense_Total_1D'
)


# =========================================================
# DATE HELPERS
# =========================================================

def _to_date(value):
    """
    Convert supported date values into a date object.

    Supported values:

        date
        datetime
        ISO date string
    """

    if isinstance(value, datetime):
        return value.date()

    if isinstance(value, date):
        return value

    if isinstance(value, str):

        try:
            return date.fromisoformat(
                value[:10]
            )

        except ValueError:
            return None

    return None


# =========================================================
# VALUE HELPERS
# =========================================================

def _is_missing(value):
    """
    Return True when a target value is missing.

    Handles:

        None
        NaN
    """

    if value is None:
        return True

    if isinstance(value, float):

        return math.isnan(value)

    return False


def _is_numeric(value):
    """
    Return True when value is numeric.
    """

    return isinstance(
        value,
        (
            int,
            float,
        ),
    ) and not isinstance(
        value,
        bool,
    )


# =========================================================
# DATE INDEX
# =========================================================

def _build_date_index(rows):
    """
    Build a lookup table indexed by Date.
    """

    index = {}

    for row in rows:

        row_date = _to_date(
            row.get('Date')
        )

        if row_date is None:
            continue

        index[row_date] = row

    return index


# =========================================================
# TARGET VALIDATION
# =========================================================

def validate_target_name(
    target_name,
):
    """
    Validate that a target is generated by the target system.
    """

    if not target_name:
        raise ValueError(
            'Target name is required.'
        )

    available_targets = set(
        get_target_names()
    )

    if target_name not in available_targets:

        raise ValueError(
            f'Unknown target: {target_name}\n'
            'Use get_target_names() to see '
            'the available targets.'
        )

    return target_name


# =========================================================
# PREPARED DATA
# =========================================================

def get_model_prepared_data():
    """
    Return the unified prepared dataset.

    This function exists as a single explicit entry point
    for the training pipeline.
    """

    prepared_data = (
        get_prepared_dataset()
    )

    if prepared_data is None:
        return []

    return sorted(
        prepared_data,
        key=lambda row: row['Date'],
    )


# =========================================================
# FEATURE DATASET
# =========================================================

def build_feature_dataset():
    """
    Build the historical feature dataset.

    Feature construction is delegated to:

        ml.features.build

    This keeps Feature Engineering separate from
    Training Dataset construction.
    """

    feature_dataset = (
        build_feature_training_dataset()
    )

    if feature_dataset is None:
        return []

    return sorted(
        feature_dataset,
        key=lambda row: row['Date'],
    )


# =========================================================
# TARGET DATASET
# =========================================================

def build_target_dataset():
    """
    Build the complete future-oriented target dataset.

    Target construction is delegated to:

        ml.targets.build
    """

    prepared_data = (
        get_model_prepared_data()
    )

    if not prepared_data:
        return []

    target_dataset = (
        get_target_dataset(
            prepared_data
        )
    )

    validate_target_dataset(
        target_dataset
    )

    return target_dataset


# =========================================================
# MERGE FEATURES + TARGETS
# =========================================================

def merge_feature_and_target_data(
    feature_dataset,
    target_dataset,
    target_name,
):
    """
    Merge feature rows with one selected target.

    IMPORTANT:

        Features are indexed by Date.

        Targets are also indexed by Date.

    Therefore:

        Feature Date = T

        Target_XXX_1D = outcome at T+1

        Target_XXX_7D = outcome at T+7

        Target_XXX_8_15D = aggregate outcome
        from T+8 through T+15

    No row-position assumption is used.
    """

    validate_target_name(
        target_name
    )

    if not feature_dataset:
        return []

    if not target_dataset:
        return []

    target_index = _build_date_index(
        target_dataset
    )

    merged = []

    for feature_row in feature_dataset:

        current_date = _to_date(
            feature_row.get('Date')
        )

        if current_date is None:
            continue

        target_row = target_index.get(
            current_date
        )

        if target_row is None:
            continue

        if target_name not in target_row:
            continue

        row = dict(
            feature_row
        )

        row[target_name] = (
            target_row[target_name]
        )

        merged.append(
            row
        )

    return merged


# =========================================================
# TARGET AVAILABILITY
# =========================================================

def filter_available_target_rows(
    dataset,
    target_name,
):
    """
    Keep only rows where the selected target is known.

    Future rows whose target cannot yet be observed are
    represented by NaN and must not enter supervised
    training.

    This is especially important for:

        T+7
        T+8...15
        T+16...30
        T+1...30
    """

    validate_target_name(
        target_name
    )

    result = []

    for row in dataset:

        value = row.get(
            target_name
        )

        if _is_missing(value):
            continue

        result.append(
            row
        )

    return result


# =========================================================
# FEATURE NAME EXTRACTION
# =========================================================

def get_model_feature_names(
    dataset,
):
    """
    Return feature names allowed to enter the model.

    Excluded:

        Date
        Target columns
    """

    if not dataset:
        return []

    return [
        key
        for key in dataset[0].keys()
        if key != 'Date'
        and not key.startswith(
            'Target_'
        )
    ]


# =========================================================
# NUMERIC FEATURE VALIDATION
# =========================================================

def validate_numeric_features(
    dataset,
    feature_names,
):
    """
    Ensure all model input features are numeric.

    The training layer should not silently pass text values
    into scikit-learn models.

    Categorical transformations belong to Feature Engineering,
    not this dataset assembly layer.
    """

    if not dataset:
        return

    for row_index, row in enumerate(
        dataset
    ):

        for feature_name in feature_names:

            value = row.get(
                feature_name
            )

            if value is None:
                continue

            if not _is_numeric(
                value
            ):

                raise ValueError(
                    'Non-numeric feature detected.\n'
                    f'Row: {row_index}\n'
                    f'Feature: {feature_name}\n'
                    f'Value: {value!r}'
                )


# =========================================================
# TARGET TYPE INSPECTION
# =========================================================

def infer_target_type(
    dataset,
    target_name,
):
    """
    Infer the basic target type.

    Returns:

        numeric
        categorical
        unknown

    This does NOT select the model.

    Model selection belongs to the training/model layer.
    """

    validate_target_name(
        target_name
    )

    values = [
        row.get(target_name)
        for row in dataset
        if not _is_missing(
            row.get(target_name)
        )
    ]

    if not values:
        return 'unknown'

    if all(
        _is_numeric(value)
        for value in values
    ):
        return 'numeric'

    return 'categorical'


# =========================================================
# SUPERVISED DATASET
# =========================================================

def prepare_model_dataset(
    target_name=DEFAULT_TARGET_NAME,
):
    """
    Build the complete supervised-learning dataset for
    one selected target.

    Architecture:

        Prepared Data
             │
             ├── Features
             │
             └── Targets
                    │
                    ▼
              Merge by Date
                    │
                    ▼
             Remove unknown targets
                    │
                    ▼
             Chronological split
                    │
             ┌──────┴──────┐
             ▼             ▼
          X_train       X_test
          y_train       y_test

    IMPORTANT:

        target_name is selected explicitly.

        This allows the system to train specialized models
        for different targets.
    """

    validate_target_name(
        target_name
    )

    # -----------------------------------------------------
    # Build Features
    # -----------------------------------------------------

    feature_dataset = (
        build_feature_dataset()
    )

    if not feature_dataset:
        return _empty_model_dataset(
            target_name
        )

    # -----------------------------------------------------
    # Build Targets
    # -----------------------------------------------------

    target_dataset = (
        build_target_dataset()
    )

    if not target_dataset:
        return _empty_model_dataset(
            target_name
        )

    # -----------------------------------------------------
    # Merge by actual calendar date
    # -----------------------------------------------------

    merged_dataset = (
        merge_feature_and_target_data(
            feature_dataset,
            target_dataset,
            target_name,
        )
    )

    if not merged_dataset:
        return _empty_model_dataset(
            target_name
        )

    # -----------------------------------------------------
    # Remove rows whose future target is not yet known
    # -----------------------------------------------------

    supervised_dataset = (
        filter_available_target_rows(
            merged_dataset,
            target_name,
        )
    )

    if not supervised_dataset:
        return _empty_model_dataset(
            target_name
        )

    # -----------------------------------------------------
    # Chronological ordering
    # -----------------------------------------------------

    supervised_dataset.sort(
        key=lambda row: row['Date']
    )

    # -----------------------------------------------------
    # Feature names
    # -----------------------------------------------------

    feature_names = (
        get_model_feature_names(
            supervised_dataset
        )
    )

    if not feature_names:
        raise ValueError(
            'No model features are available.'
        )

    # -----------------------------------------------------
    # Numeric validation
    # -----------------------------------------------------

    validate_numeric_features(
        supervised_dataset,
        feature_names,
    )

    # -----------------------------------------------------
    # Build X / y
    # -----------------------------------------------------

    X = []
    y = []

    for row in supervised_dataset:

        X.append([
            row.get(
                feature_name
            )
            for feature_name in feature_names
        ])

        y.append(
            row.get(
                target_name
            )
        )

    # -----------------------------------------------------
    # Chronological train/test split
    #
    # No random shuffle.
    #
    # Historical order must be preserved.
    # -----------------------------------------------------

    split_index = _calculate_split_index(
        len(supervised_dataset)
    )

    X_train = X[
        :split_index
    ]

    y_train = y[
        :split_index
    ]

    X_test = X[
        split_index:
    ]

    y_test = y[
        split_index:
    ]

    training_data = (
        supervised_dataset[
            :split_index
        ]
    )

    test_data = (
        supervised_dataset[
            split_index:
        ]
    )

    # -----------------------------------------------------
    # Validation report
    # -----------------------------------------------------

    validation_report = {
        'target_name':
            target_name,

        'target_type':
            infer_target_type(
                supervised_dataset,
                target_name,
            ),

        'total_rows':
            len(supervised_dataset),

        'training_rows':
            len(training_data),

        'test_rows':
            len(test_data),

        'feature_count':
            len(feature_names),

        'first_date':
            supervised_dataset[0][
                'Date'
            ],

        'last_date':
            supervised_dataset[-1][
                'Date'
            ],

        'train_first_date':
            training_data[0][
                'Date'
            ]
            if training_data
            else None,

        'train_last_date':
            training_data[-1][
                'Date'
            ]
            if training_data
            else None,

        'test_first_date':
            test_data[0][
                'Date'
            ]
            if test_data
            else None,

        'test_last_date':
            test_data[-1][
                'Date'
            ]
            if test_data
            else None,
    }

    return {
        'dataset':
            supervised_dataset,

        'feature_names':
            feature_names,

        'target_name':
            target_name,

        'training_rows':
            len(training_data),

        'test_rows':
            len(test_data),

        'training_data':
            training_data,

        'test_data':
            test_data,

        'X_train':
            X_train,

        'y_train':
            y_train,

        'X_test':
            X_test,

        'y_test':
            y_test,

        'validation_report':
            validation_report,
    }


# =========================================================
# SPLIT HELPER
# =========================================================

def _calculate_split_index(
    total_rows,
):
    """
    Calculate a chronological train/test split.

    Uses approximately 80% for training and 20% for testing.

    At least one row is reserved for testing whenever the
    dataset contains enough observations.
    """

    if total_rows < 2:
        return total_rows

    split_index = int(
        total_rows * 0.80
    )

    split_index = max(
        1,
        split_index,
    )

    split_index = min(
        total_rows - 1,
        split_index,
    )

    return split_index


